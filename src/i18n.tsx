const dicts: Record<Lang, Record<Key, string>> = { pl, en };

export type T = (key: Key, vars?: Record<string, string | number>) => string;

export function makeT(lang: Lang): T {
  return (key, vars) => {
    let s = dicts[lang][key] ?? key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
    return s;
  };
}

export const LangContext = createContext<{ lang: Lang; t: T }>({ lang: 'pl', t: makeT('pl') });
export const useT = () => useContext(LangContext).t;
export const useLang = () => useContext(LangContext).lang;
export const errorKey = (code: ErrorCode) => `error.${code}` as Key;
